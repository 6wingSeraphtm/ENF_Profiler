#pragma once
#include <string_view>

// Чей это код: из пути исходника достаём имя мода.
//
// Путь приходит из отладочной информации движка: `Funct -> DebugOffset ->
// DebugInfo::m_Lines[off].m_iModule -> m_Modules[i].m_strName`. Это ЕДИНСТВЕННЫЙ
// достоверный источник принадлежности — ни класс, ни модуль (`3_Game`, `4_World`) мода
// не называют, а цепочка наследования говорит о базе, а не о том, кто её переопределил.
//
// Раскладка, из которой растёт правило: ваниль лежит в корне (`scripts/<слой>/...`), а
// мод — под своим PBO-префиксом (`TraderPlus/scripts/<слой>/...`). Значит первый сегмент
// пути и есть ответ, кроме случая, когда это сам `scripts`.
namespace krprof {

// Ваниль: своего префикса у неё нет. Отдельное имя, а не пустая строка, — потому что в
// отчёте это полноправная строка, и «сколько времени ест сама игра» такой же вопрос,
// как и про любой мод.
inline constexpr std::string_view vanilla_mod = "$vanilla";

// Путь не разобрался. Символизация читает чужую память, и мусор там — штатный исход,
// а не повод падать. Он должен быть ВИДЕН в отчёте, а не свален в ваниль: иначе разбор
// раскладки, который поехал после патча игры, выглядел бы как подорожавшая ваниль.
inline constexpr std::string_view unknown_mod = "$unknown";

// Функция самого движка: `proto`/`proto native`, объявленная в C++. Исходника у неё нет
// и быть не может, поэтому в `$unknown` ей не место — это не провал разбора, а честный
// ответ. Ванильный EnProfiler такие не считает вовсе ("'proto' methods are not
// tracked"), и это одна из причин, по которым он не показывает, куда ушло время.
inline constexpr std::string_view engine_mod = "$engine";

// Натив, вызванный ИЗ скрипта: у него есть скриптовое имя (`GetPlayers`), но нет
// исходника — он объявлен в C++. Отделён от `$engine` намеренно: это граница между
// мирами, и по ней видно, сколько скрипт тратит на обращения к движку.
inline constexpr std::string_view proto_mod = "$proto";

// Имя мода по пути исходника.
//
// Возвращает вьюху В ПЕРЕДАННУЮ строку (или в статику для двух имён выше) — своего
// буфера не заводит и не аллоцирует: зовётся на символизации каждого нового кадра.
// Значит `path` обязан пережить результат. У нас переживает: строки лежат в `DebugInfo`
// движка и живут столько же, сколько скомпилированные скрипты.
[[nodiscard]] std::string_view mod_of(std::string_view path) noexcept;

// Полный префикс — всё, что стоит перед меткой (`KR/diag/KR_GUARANA`). В отличие от
// короткого имени он верен ВСЕГДА, поэтому уезжает в сайдкар: там, где `mod_of` не смог
// отделить подкаталог мода от его префикса, правду видно по нему.
[[nodiscard]] std::string_view prefix_of(std::string_view path) noexcept;

}  // namespace krprof
