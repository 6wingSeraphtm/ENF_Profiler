#pragma once
#include <string_view>

// Сэмплер: свой поток, который периодически останавливает игровой цикл, снимает стек
// кадров и отпускает. Символизация и укладка в дерево идут ПОСЛЕ возобновления — под
// приостановкой не делается ничего, кроме копирования указателей.
//
// Своего потока требует сама природа задачи: снять стек с того же потока, который его
// снимает, нельзя. PBO при этом не нужен — поток запускается из точки входа плагина.
namespace krprof::sampler {

using log_fn = void (*)(std::string_view);

// Прогон: найти раскладку, снять `seconds` секунд на частоте `hz`, выгрузить отчёт.
void run(unsigned hz, unsigned seconds, log_fn say);

// Досрочно прекратить (зовётся с чужого потока).
void stop();

// Выгрузить то, что накоплено: `<имя>.folded` и `<имя>.json` рядом с exe игры.
void dump(log_fn say);

}  // namespace krprof::sampler
