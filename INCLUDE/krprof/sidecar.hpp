#pragma once
#include <cstdint>
#include <string>

#include "krprof/call_tree.hpp"
#include "krprof/symbols.hpp"

// Сайдкар к свёрнутым стекам: метаданные прогона и сводка по модам.
//
// Формат свёрнутых стеков не несёт ничего, кроме имён и весов, — и это его достоинство,
// за него его и читают все просмотрщики. Всё остальное едет рядом отдельным JSON:
// сколько снято, за сколько, и во что обошёлся каждый мод.
namespace krprof {

struct run_meta {
    std::uint64_t samples = 0;    // сколько снимков легло в дерево
    std::uint32_t sample_hz = 0;  // с какой частотой просили снимать
    std::uint64_t wall_ms = 0;    // сколько шёл прогон
    // Снимки, которые снять не удалось: поток не остановился, стек оказался неразумной
    // глубины, машина ещё не найдена. Число обязано быть на виду — молча потерянные
    // снимки означают, что флеймграф врёт, и об этом надо знать, а не догадываться.
    std::uint64_t dropped = 0;
    // Снимки, снятые со стека ОС, когда скрипт молчал. Отдельным числом: это другой мир
    // и другая методика, смешивать их в «снимках» значило бы путать читателя.
    std::uint64_t engine_samples = 0;

    // ── Покадровое ───────────────────────────────────────────────────────────
    // Игра однопоточна и идёт кадрами, поэтому «какой кадр был долгим» — отдельный
    // вопрос, а не следствие суммарной таблицы.
    //
    // Кадр опознаётся как ЭПИЗОД ИСПОЛНЕНИЯ: стек скрипта был пуст, стал непустым.
    // Между кадрами движок занят не скриптом, поэтому стек там пуст. Признак косвенный,
    // и потому рядом печатается `frames_per_s` — по нему видно, похоже ли это на FPS
    // сервера, или эпизоды дробятся и считать их кадрами нельзя.
    std::uint64_t frames = 0;
    std::uint64_t worst_frame_us = 0;   // самый долгий эпизод
    std::uint64_t median_frame_us = 0;
};

// Сводка по модам считается по СОБСТВЕННОМУ весу кадров: время, ушедшее в `super` или в
// чужой вызов, принадлежит тому, кто его исполнял, а не тому, кто позвал. Иначе мод из
// одной строки `super.OnUpdate()` выглядел бы самым дорогим в игре.
[[nodiscard]] std::string to_sidecar_json(const call_tree& tree,
                                          const symbol_table& symbols,
                                          const run_meta& meta);

}  // namespace krprof
