#pragma once
#include <cstdint>
#include <span>
#include <string>
#include <vector>

// Стек ОС приостановленного игрового потока — то, чего не видно в скриптовом стеке.
//
// ЗАЧЕМ. Скриптовый стек покрывает около трети времени сервера; остальные две трети
// движок занят не скриптом, и там у профайлера была полная слепота. Здесь она и
// закрывается.
//
// ЧТО МОЖНО И ЧЕГО НЕЛЬЗЯ С ИМЕНАМИ. Проверено по бинарю DayZDiag 1.29:
//   * PDB рядом нет — только путь на сборочную машину в debug-каталоге;
//   * экспортов у exe РОВНО ТРИ (они манглированы, demangle к ним применим и работает,
//     но три имени профайлеру бесполезны);
//   * зато `.pdata` несёт 68 129 записей раскрутки — значит границы функций точны и
//     `RtlVirtualUnwind` работает.
// Отсюда честный вывод: имена движковых функций взять неоткуда, а вот АДРЕС НАЧАЛА
// функции — точен. Кадр называется `DayZDiag_x64.exe+0x3485A0`: это устойчивый
// идентификатор, по нему функция ищется в IDA и он не двоится между прогонами.
// Системные библиотеки экспортируют имена, и там dbghelp их даёт — уже с demangle.
namespace krprof::native {

// Сырой снимок: регистры и КОПИЯ куска стека.
struct snapshot {
    std::uint64_t rip = 0;
    std::uint64_t rsp = 0;
    std::vector<std::byte> bytes;
};

// Снять снимок. Зовётся, ПОКА ПОТОК СТОИТ, и делает только копирование — ни разбора, ни
// поиска, ни блокировок.
//
// Это правило оплачено падением сервера: первая версия разматывала стек `RtlVirtualUnwind`
// уже после возобновления, по живой меняющейся памяти, и уронила процесс. Плюс
// `RtlLookupFunctionEntry` берёт блокировку таблицы функций загрузчика — если её держит
// приостановленный поток, это взаимоблокировка намертво.
[[nodiscard]] std::size_t capture_stack(void* thread, snapshot& out);

// Разобрать снимок. Зовётся ПОСЛЕ возобновления, когда всё безопасно.
//
// Проход консервативный: берём из копии стека всё, что похоже на адрес возврата. Это не
// настоящая раскрутка, и среди найденного будут остатки прошлых вызовов. Приблизительный,
// но безопасный ответ здесь лучше точного, который роняет сервер.
[[nodiscard]] std::size_t walk(const snapshot& snap, std::vector<void*>& out,
                               std::size_t limit);

// Имя кадра по адресу возврата. Дорого (dbghelp, разбор модулей), поэтому зовётся один
// раз на уникальный адрес — снаружи окна остановки.
[[nodiscard]] std::string name_of(void* addr);

// Начало функции, которой принадлежит адрес: из таблицы раскрутки. Нужно, чтобы все
// адреса внутри одной функции схлопывались в один кадр, а не рассыпались по строкам.
[[nodiscard]] void* function_start(void* addr);

}  // namespace krprof::native
