#pragma once
#include <cstdint>
#include <string_view>
#include <vector>

#include "krprof/native_stack.hpp"

// Движковая половина: раскладка чужих структур и снятие стека.
//
// Отделена от ядра намеренно. Ядро (дерево, символы, эмиттеры) движка не знает вовсе и
// потому проверяется тестами без игры; всё, что требует живого сервера, живёт здесь.
//
// ЗАШИТЫХ АДРЕСОВ НЕТ. Точки входа и раскладку скриптовой машины уже нашёл `graft::mt` —
// от якоря `ScriptModule.Call`, по call-графу, со сверкой сигнатур. Мы добираем то, что
// mt не искал, потому что ему было не нужно: раскладку КАДРА и раскладку `Funct`.
namespace krprof::engine {

using log_fn = void (*)(std::string_view);

// Один снятый кадр — ровно то, что успеваем скопировать под приостановкой.
// Разбирать эти указатели будем ПОСЛЕ возобновления: пока поток стоит, любая лишняя
// работа оплачивается кадром сервера.
struct raw_frame {
    // Текущая инструкция. Именно от неё движок считает позицию в исходнике — не от
    // `Funct`. Значит и строка получается ТЕКУЩАЯ, а не первая строка функции.
    void* stat = nullptr;
    void* funct = nullptr;
    void* object = nullptr;
};

struct layout {
    unsigned frame_stat = ~0u;      // кадр -> Stat* (текущая инструкция)
    unsigned frame_func = ~0u;      // кадр -> Funct*
    unsigned frame_object = ~0u;    // кадр -> Instance*
    unsigned funct_name = ~0u;      // Funct -> const char*

    // Цепочка до исходного файла. Это ЕДИНСТВЕННЫЙ достоверный источник «чей это код»:
    // ни класс, ни скриптовый модуль (3_Game, 4_World) мода не называют, а цепочка
    // наследования говорит о базе, а не о том, кто её переопределил.
    //
    //   Funct -> Module -> DebugInfo -> m_Lines[Funct.DebugOffset].m_iModule
    //                                -> m_Modules[...] -> путь к .c
    unsigned funct_module = ~0u;
    unsigned funct_debug_off = ~0u;
    unsigned module_debug = ~0u;   // ScriptModule -> DebugInfo*
    unsigned dbg_modules = ~0u;    // DebugInfo -> const char** (массив путей)
    unsigned dbg_module_count = ~0u;
    unsigned dbg_lines = ~0u;      // DebugInfo -> Line* (8 байт на запись)
    unsigned dbg_line_count = ~0u;
    // Строка в движке — `BaseString<CStrTraits>`: ОДИН указатель на заголовок
    // `Rep { uint Length; uint Cap; char Data[1]; }`. То есть запись таблицы путей —
    // не `char*`, а `Rep*`, и символы лежат ВНУТРИ него. Именно на этом три захода
    // поиска по памяти и разбились: указатель проверялся как строка напрямую.
    unsigned str_payload = ~0u;

    [[nodiscard]] bool ok() const noexcept {
        return frame_func != ~0u && funct_name != ~0u;
    }

    // Отладочная информация — не обязательное условие работы: без неё профиль всё равно
    // строится, просто все кадры уедут в `$unknown`. Поэтому отдельный признак.
    [[nodiscard]] bool has_debug() const noexcept {
        return funct_module != ~0u && dbg_modules != ~0u && dbg_lines != ~0u;
    }
};

[[nodiscard]] const layout& found() noexcept;

// Заведомо годный `Funct*`, пойманный зондом кадра. От него пляшет поиск отладочной
// информации: искать её от произвольного указателя было бы не с чего начать.
[[nodiscard]] void* probe_sample() noexcept;

// Набор заведомо годных `Funct*`, собранный зондом с живого стека. Одного образца для
// поиска `DebugOffset` мало: у любого одиночного указателя найдётся несколько смещений,
// дающих правдоподобный путь. Правильное поле — то, что работает на ВСЕЙ выборке.
[[nodiscard]] const std::vector<raw_frame>& probe_samples() noexcept;

namespace detail {
// Раскладку заполняют два файла — engine.cpp и debug_info.cpp. Общий неконстантный
// доступ вместо const_cast: он был бы законен, но врал бы про намерение.
[[nodiscard]] layout& mutable_layout() noexcept;
}  // namespace detail

// ── Работа с игровым потоком ─────────────────────────────────────────────────
// Открыть поток игрового цикла. Его опознаёт graft::mt — по самому раннему потоку
// процесса, а не по приметам.
[[nodiscard]] void* open_game_thread();

// Снять стек: приостановить поток, скопировать кадры, возобновить.
// Возвращает глубину; `out` заполняется снаружи внутрь (out[0] — самый внешний кадр).
// Под приостановкой не делается НИЧЕГО, кроме копирования.
std::size_t capture(void* thread, std::vector<raw_frame>& out);

// Сколько игровой поток простоял в окнах остановки. Это ВСЯ цена профайлера для сервера:
// снаружи окна мы работаем на своём ядре и серверу не мешаем. Меряется на живом потоке
// DayZ, а не на модели, — синтетика показывала 9.8 мкс, но верить надо игре.
struct window_stats {
    std::uint64_t count = 0;
    std::uint64_t total_us = 0;
    std::uint64_t median_us = 0;
    std::uint64_t p99_us = 0;
    std::uint64_t max_us = 0;
};

[[nodiscard]] window_stats windows();

// Почему снимок не лёг в профиль. Числа обязаны быть на виду: молча пропущенные снимки
// означают, что флеймграф врёт, и об этом надо знать, а не догадываться.
struct skip_stats {
    std::uint64_t no_thread = 0;    // текущего скриптового потока нет вовсе
    std::uint64_t not_running = 0;  // поток есть, но он СПИТ (Sleep/Wait)
    std::uint64_t empty = 0;        // поток исполняется, но стек пуст
    // Снимок ПОРВАЛСЯ: глубина стека изменилась, пока мы его копировали. Значит поток
    // не встал, и прочитанное — смесь двух моментов. Такой снимок нельзя чинить, его
    // можно только выбросить; но знать их долю обязательно, иначе профиль врёт молча.
    std::uint64_t torn = 0;
    // Кадр не прошёл проверку на `Funct`: указатель не ведёт к разумному имени.
    // Ноль здесь — сильный довод, что стек читается целиком и верно.
    std::uint64_t bad_frames = 0;
    std::uint64_t checked_frames = 0;
    // На какой глубине встретился негодный кадр. Если они кучкуются на вершине — это
    // кадр, который движок как раз заполняет; если размазаны — рвётся весь стек.
    std::uint64_t bad_at_top = 0;      // самый внутренний
    std::uint64_t bad_at_bottom = 0;   // самый внешний
    std::uint64_t bad_middle = 0;
    // Стек ОС: сколько раз пробовали снять и сколько раз вышло. Без этих чисел «мало
    // движковых кадров» не отличить от «движок и правда почти не работает».
    std::uint64_t native_tries = 0;
    std::uint64_t native_ok = 0;
    std::uint64_t native_frames = 0;
    // Гистограмма состояний потока. Нужна не для красоты: цена ошибки здесь — целый
    // класс нагрузок, молча выпавший из профиля. Состояния движка:
    //   1 TF_NONWAITABLE  исполняется, усыпить нельзя  <- обычный вызов из движка
    //   2 TF_RUNNING      исполняется, усыпить можно   <- корутина в работе
    //   3 TF_WTIME        спит по Sleep
    //   4 TF_WCOND        ждёт по Wait
    //   5 TF_KILL         разобран
    std::uint64_t by_state[8] = {};
};

[[nodiscard]] skip_stats skips();

// Снять стек ОС игрового потока: приостановить, СКОПИРОВАТЬ, возобновить. Разбор копии
// делает `native::walk` уже снаружи окна. Разделение не косметическое — под
// приостановкой нельзя ни искать записи раскрутки, ни падать.
[[nodiscard]] bool capture_native(void* thread, native::snapshot& out);

// Найти раскладку кадра: ловим момент, когда стек не пуст, и опознаём `Funct*` по тому,
// что по нему читается разумное имя. Проверка самосогласованная — случайный указатель
// её не пройдёт. Возвращает false, если за отведённые попытки скрипт так и не пошёл.
bool probe(void* thread, log_fn say);

// ── Символизация ─────────────────────────────────────────────────────────────
// Зовётся один раз на уникальный кадр (дальше работает мемоизация в symbol_table),
// поэтому может позволить себе ходить по указателям.
[[nodiscard]] std::string_view funct_name(void* funct);
[[nodiscard]] std::string_view class_name(void* object);

// Откуда объявлена функция: путь к .c и строка. Пусто, если отладочная информация не
// разобрана или у функции её нет (нативы объявлены в C++, исходника у них нет).
struct source_ref {
    std::string_view file;
    std::uint32_t line = 0;
};

[[nodiscard]] source_ref source_of_frame(void* funct, void* stat);

// Разобрать цепочку до отладочной информации. Зовётся после probe(); `sample` — любой
// заведомо годный `Funct*`, от него и пляшет поиск.
bool probe_debug(log_fn say);

// Натив ли это — то есть функция движка, объявленная в C++. Исходника у неё нет, и в
// отчёте она обязана называться движком, а не «неизвестно»: `EnProfiler` таких не
// считает вовсе, а нам их видеть НУЖНО.
[[nodiscard]] bool is_native(void* funct);

}  // namespace krprof::engine
